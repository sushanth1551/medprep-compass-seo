"""Simple data containers shared by the whole app (standard library only)."""

from dataclasses import dataclass, field
from typing import Optional

# Output-token limit used when MAX_OUTPUT_TOKENS is not set. Reasoning models spend output
# tokens on thinking as well as on the article, so this is well above a 900-word article.
DEFAULT_MAX_OUTPUT_TOKENS = 8000
DEMO_NOTICE = "DEMO CONTENT — review facts and sources before publication."
DRAFT_NOTICE = (
    "AI-GENERATED DRAFT — requires human review. Facts and sources have NOT been "
    "verified. Do not publish without an expert check."
)


class ValidationError(ValueError):
    """Raised when the topic or keyword is not acceptable."""


class ConfigError(Exception):
    """Raised when the provider settings are missing or invalid."""


class ProviderError(Exception):
    """Raised when an AI provider request fails. The message is safe to print."""


@dataclass
class OutlineSection:
    heading: str
    purpose: str


@dataclass
class Article:
    title: str
    meta_description: str
    keyword: str
    sections: list  # list of (heading, body) tuples; a body may contain "### " sub-headings
    faq: list  # list of (question, answer) tuples
    provider_name: str = "unknown"
    notice: str = DEMO_NOTICE
    search_intent: str = ""
    audience: str = ""
    # [{"title": str, "url": str, "claim": str}] as proposed by the model. NOT verified.
    references: list = field(default_factory=list)
    review_flags: list = field(default_factory=list)  # claims the writer marked as uncertain
    run_id: str = ""  # ties the file to its metrics and report
    revision: int = 1

    def to_markdown(self) -> str:
        lines = [f"# {self.title}", "", f"> {self.notice}", ""]
        lines += [f"**Meta description:** {self.meta_description}", ""]
        lines += [f"**Target keyword:** {self.keyword}", ""]
        if self.search_intent:
            lines += [f"**Search intent:** {self.search_intent}", ""]
        if self.audience:
            lines += [f"**Audience:** {self.audience}", ""]
        lines += [f"**Generated by provider:** {self.provider_name}", ""]
        if self.run_id:
            lines += [f"**Run ID:** {self.run_id} | **Revision:** {self.revision}", ""]
        for heading, body in self.sections:
            lines += [f"## {heading}", "", body, ""]
        lines += ["## Frequently Asked Questions", ""]
        for question, answer in self.faq:
            lines += [f"### {question}", "", answer, ""]
        has_refs_section = any(h.strip().lower() == "references" for h, _ in self.sections)
        if self.references and not has_refs_section:
            lines += ["## References", ""]
            for n, ref in enumerate(self.references, 1):
                lines.append(f"{n}. {ref.get('title') or 'Untitled source'}. {ref.get('url', '')}")
            lines.append("")
        return "\n".join(lines)


@dataclass
class UsageInfo:
    """Token usage. `usage_source` says whether the numbers are real or guesses."""

    estimated_input_tokens: int = 0
    estimated_output_tokens: int = 0
    # None means "unknown" (no pricing configured). It is never silently 0.
    estimated_cost: Optional[float] = None
    cost_note: str = "Cost is unknown: no pricing is configured."
    is_estimate: bool = True
    # Filled only when a real provider reported usage. None means "not reported".
    actual_input_tokens: Optional[int] = None
    actual_output_tokens: Optional[int] = None
    cached_input_tokens: Optional[int] = None
    usage_source: str = "estimated"  # "estimated" | "actual" | "unavailable"

    @property
    def source_label(self) -> str:
        if self.usage_source == "actual":
            return "ACTUAL (reported by the API)"
        if self.usage_source == "unavailable":
            return "UNAVAILABLE (the API did not report usage)"
        return "ESTIMATE (about 4 characters per token)"


@dataclass
class SeoReport:
    """Result of the deterministic checklist. NOT a Google ranking score."""

    passed: list = field(default_factory=list)  # messages
    warnings: list = field(default_factory=list)
    failed: list = field(default_factory=list)
    word_count: int = 0
    readability: dict = field(default_factory=dict)
    claims_needing_evidence: list = field(default_factory=list)  # sentences
    references_found: list = field(default_factory=list)
    # Nothing in this app checks whether a source exists or supports a claim.
    source_verification: str = "NOT PERFORMED - a human must verify every fact and source"
    needs_human_review: bool = True

    @property
    def total_checks(self) -> int:
        return len(self.passed) + len(self.warnings) + len(self.failed)

    @property
    def score_text(self) -> str:
        return (
            f"{len(self.passed)}/{self.total_checks} checklist items passed "
            "(simple checklist count, not a Google ranking score)"
        )


@dataclass
class WorkflowResult:
    article: Article
    output_path: str
    usage: UsageInfo
    check_results: dict = field(default_factory=dict)
    seo_report: Optional["SeoReport"] = None
    report_path: str = ""
    metrics: Optional[dict] = None
    metrics_path: str = ""

    @property
    def checks_passed(self) -> bool:
        return all(self.check_results.values())
